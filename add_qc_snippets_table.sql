-- ============================================

-- 1. 建表
CREATE TABLE IF NOT EXISTS qc_snippets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('correct', 'knowledge')),
  category TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_default BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  created_by TEXT DEFAULT ''
);

-- 2. 索引
CREATE INDEX IF NOT EXISTS idx_qc_snippets_type ON qc_snippets(type);
CREATE INDEX IF NOT EXISTS idx_qc_snippets_sort ON qc_snippets(sort_order);

-- 3. RLS
ALTER TABLE qc_snippets ENABLE ROW LEVEL SECURITY;

-- 所有人可读（客服可插入话术）
CREATE POLICY "Allow public read on qc_snippets"
ON qc_snippets FOR SELECT
TO anon, authenticated
USING (true);

-- 登录用户可增删改（页面仅管理员可见管理入口，RLS 保持与 qc_records 一致）
CREATE POLICY "Allow authenticated write on qc_snippets"
ON qc_snippets FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

